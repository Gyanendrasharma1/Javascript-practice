// Logical operators

//1. Logical AND (&&)
let a =  9;
let b = 10;

console.log(a && b);


//2. Logical OR (||)
let hasticket = false;
let haspass   = true;

console.log(hasticket || haspass);

//3. Logical NOT (!)
let isloggedin = false;
let isloggedout = !isloggedin; // true
console.log(isloggedout);