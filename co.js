// Comparison Operators in JavaScript

// STEP-1 equality operator (==)
let a = 90;
let b = 10;

console.log("== equal to:");
console.log(a==b);

//STEP-2 strict equality operator (===)

console.log("=== strict equal to:");
console.log(a===b);

//STEP-3 not equal to (!=)
console.log("!= not equal to:");
console.log(a!=b);

// STEP-4 strict not equal to (!==)
console.log("!== not equal to:");
console.log(a!=b);

// STEP-5 greater than (>)
console.log("> greater than:");
console.log(a>b);

// STEP-6 less than (<)
console.log("< less than:");
console.log(a<b);

// STEP-7 greater than or equal to (>=)
console.log(">= greater than or equal to:");
console.log(a>=b);

// STEP-8 less than or equal to (<=)
console.log("<= lesser than or equal to:");
console.log(a<=b);



